# Function to detect data gaps between database and FTS portal
detect_data_gaps <- function(
  lookback_days = 365,           # How many days back to check
  start_date = NULL,            # Custom start date (overrides lookback_days)
  end_date = NULL,              # Custom end date (defaults to today)
  stations = "Daring FTS",             # Which stations to check ("all" or vector of station names)
  variables = "T_AIR_HIGH_C"             # Which variables to check ("all" or vector of variable names)
) {
  
  cat("🔍 Detecting data gaps...\n")
  
  # Set date range
  if (is.null(end_date)) {
    end_date <- Sys.Date()
  }
  if (is.null(start_date)) {
    start_date <- end_date - lookback_days
  }
  
  cat("📅 Checking period:", as.character(start_date), "to", as.character(end_date), "\n")
  
  # Get all FTS stations from database
  fts_stations <- cd_stations %>% 
    dplyr::filter(grepl("FTS$", STATION_NAME)) %>%
    dplyr::select(STATION_ID, STATION_NAME)
  
  if (stations != "all") {
    fts_stations <- fts_stations %>% 
      dplyr::filter(STATION_NAME %in% stations)
  }
  
  cat("🏢 Checking", nrow(fts_stations), "FTS stations\n")
  
  # Get existing data coverage from loaded tables
  # Combine all climate data tables
  all_climate_data <- dplyr::bind_rows(
    Table0 %>% dplyr::mutate(table_source = "Table0"),
    Table1 %>% dplyr::mutate(table_source = "Table1"),
    Table3 %>% dplyr::mutate(table_source = "Table3")
  )
  
  # Filter for FTS stations and date range
  existing_data <- all_climate_data %>%
    dplyr::left_join(cd_stations %>% dplyr::select(STATION_ID, STATION_NAME), by = "STATION_ID") %>%
    dplyr::left_join(cd_data_types %>% dplyr::select(DATA_TYPE_ID, DATA_TYPE), by = "DATA_TYPE_ID") %>%
    dplyr::filter(
      grepl("FTS$", STATION_NAME),
      CD_YEAR >= lubridate::year(start_date),
      CD_YEAR <= lubridate::year(end_date),
      !(CD_YEAR == lubridate::year(start_date) & CD_MONTH < lubridate::month(start_date)),
      !(CD_YEAR == lubridate::year(start_date) & CD_MONTH == lubridate::month(start_date) & CD_DAY < lubridate::day(start_date)),
      !(CD_YEAR == lubridate::year(end_date) & CD_MONTH > lubridate::month(end_date)),
      !(CD_YEAR == lubridate::year(end_date) & CD_MONTH == lubridate::month(end_date) & CD_DAY > lubridate::day(end_date))
    ) %>%
    dplyr::group_by(STATION_NAME, CD_YEAR, CD_MONTH, CD_DAY, DATA_TYPE) %>%
    dplyr::summarise(record_count = n(), .groups = "drop") %>%
    dplyr::arrange(STATION_NAME, CD_YEAR, CD_MONTH, CD_DAY, DATA_TYPE)
  
  # Create expected data coverage (every day for each station/variable combination)
  expected_dates <- seq(from = start_date, to = end_date, by = "day")
  
  # Get actual data types from the database
  actual_data_types <- unique(existing_data$DATA_TYPE)
  cat("🔍 Available DATA_TYPE values in database:\n")
  print(actual_data_types)
  
  # Map expected variable names to actual database DATA_TYPE values
  variable_mapping <- list(
    "T_AIR_HIGH_C" = "Air Temperature High",
    "RH_HIGH_PER" = "Relative Humidity High", 
    "RAIN_MM" = "Rain",
    "WIND_SP_MS" = "Wind Speed",
    "WIND_DIR_DEG" = "Wind Direction",
    "SW_IN_WM2" = "Incoming Shortwave Radiation",
    "SR50_CM" = "SR50",
    "T_SOIL_1_C" = "Ground Temperature 1",
    "T_SOIL_2_C" = "Ground Temperature 2",
    "T_SOIL_3_C" = "Ground Temperature 3"
  )
  
  # Get the actual DATA_TYPE values that exist in the database
  fts_data_types <- unlist(variable_mapping[variable_mapping %in% actual_data_types])
  
  if (variables != "all") {
    # Map the requested variables to their database names
    requested_db_types <- unlist(variable_mapping[names(variable_mapping) %in% variables])
    fts_data_types <- requested_db_types[requested_db_types %in% actual_data_types]
  }
  
  cat("🎯 Using DATA_TYPE values for gap detection:\n")
  print(fts_data_types)
  
  # Create expected coverage grid
  expected_coverage <- expand.grid(
    STATION_NAME = fts_stations$STATION_NAME,
    expected_date = expected_dates,
    DATA_TYPE = fts_data_types,
    stringsAsFactors = FALSE
  ) %>%
    dplyr::mutate(
      CD_YEAR = lubridate::year(expected_date),
      CD_MONTH = lubridate::month(expected_date),
      CD_DAY = lubridate::day(expected_date)
    ) %>%
    dplyr::select(-expected_date)
  
  # Find gaps by comparing expected vs existing
  cat("\n🔍 Debug: Expected coverage sample:\n")
  print(head(expected_coverage, 5))
  
  cat("\n🔍 Debug: Existing data sample:\n")
  print(head(existing_data, 5))
  
  gaps <- expected_coverage %>%
    dplyr::left_join(existing_data, by = c("STATION_NAME", "CD_YEAR", "CD_MONTH", "CD_DAY", "DATA_TYPE")) %>%
    dplyr::filter(is.na(record_count)) %>%
    dplyr::select(STATION_NAME, CD_YEAR, CD_MONTH, CD_DAY, DATA_TYPE) %>%
    dplyr::arrange(STATION_NAME, CD_YEAR, CD_MONTH, CD_DAY, DATA_TYPE)
  
  cat("\n🔍 Debug: After join sample:\n")
  joined_sample <- expected_coverage %>%
    dplyr::left_join(existing_data, by = c("STATION_NAME", "CD_YEAR", "CD_MONTH", "CD_DAY", "DATA_TYPE")) %>%
    head(10)
  print(joined_sample)
  
  # Group gaps by station and date ranges for efficient downloading
  if (nrow(gaps) == 0) {
    # No gaps found - create empty summary
    gap_summary <- data.frame(
      STATION_NAME = character(0),
      min_date = as.Date(character(0)),
      max_date = as.Date(character(0)),
      missing_days = integer(0),
      missing_variables = integer(0),
      stringsAsFactors = FALSE
    )
  } else {
    gap_summary <- gaps %>%
      dplyr::group_by(STATION_NAME) %>%
      dplyr::summarise(
        min_date = as.Date(paste(min(CD_YEAR), min(CD_MONTH), min(CD_DAY), sep = "-"), format = ("%Y-%m-%d")),
        max_date = as.Date(paste(max(CD_YEAR), max(CD_MONTH), max(CD_DAY), sep = "-"), format = ("%Y-%m-%d")),
        missing_days = n_distinct(CD_YEAR, CD_MONTH, CD_DAY),
        missing_variables = n_distinct(DATA_TYPE),
        .groups = "drop"
      ) %>%
      dplyr::arrange(STATION_NAME)
  }
  
  cat("📊 Gap Detection Summary:\n")
  cat("   Total missing records:", nrow(gaps), "\n")
  cat("   Stations with gaps:", nrow(gap_summary), "\n")
  
  if (nrow(gap_summary) > 0) {
    # Handle NA dates in the summary
    valid_dates <- gap_summary[!is.na(gap_summary$min_date) & !is.na(gap_summary$max_date), ]
    if (nrow(valid_dates) > 0) {
      cat("   Date range:", as.character(min(valid_dates$min_date)), "to", as.character(max(valid_dates$max_date)), "\n")
    } else {
      cat("   Date range: Contains stations with incomplete date information\n")
    }
    
    # Report stations with NA dates
    na_stations <- gap_summary[is.na(gap_summary$max_date), ]
    if (nrow(na_stations) > 0) {
      cat("   Stations with incomplete date info:", paste(na_stations$STATION_NAME, collapse = ", "), "\n")
    }
  } else {
    cat("   Date range: No gaps found\n")
  }
  
  if (nrow(gap_summary) > 0) {
    cat("\n📋 Stations with gaps:\n")
    print(gap_summary)
  } else {
    cat("✅ No gaps detected!\n")
  }
  
  return(list(
    gaps = gaps,
    gap_summary = gap_summary,
    existing_data = existing_data,
    expected_coverage = expected_coverage
  ))
}

# Function to fill detected gaps
fill_data_gaps <- function(gap_results, batch_size = 7) {
  
  if (nrow(gap_results$gap_summary) == 0) {
    cat("✅ No gaps to fill!\n")
    return(invisible(NULL))
  }
  
  cat("🔄 Starting gap filling process...\n")
  
  # Group stations by similar date ranges for batch processing
  gap_summary <- gap_results$gap_summary
  
  # Filter out stations with NA dates (they can't be processed for gap filling)
  valid_stations <- gap_summary[!is.na(gap_summary$min_date) & !is.na(gap_summary$max_date), ]
  na_stations <- gap_summary[is.na(gap_summary$min_date) | is.na(gap_summary$max_date), ]
  
  if (nrow(na_stations) > 0) {
    cat("⚠️  Skipping stations with incomplete date information:\n")
    cat("   ", paste(na_stations$STATION_NAME, collapse = ", "), "\n")
    cat("   These stations haven't been transmitting data recently.\n\n")
  }
  
  if (nrow(valid_stations) == 0) {
    cat("❌ No stations with valid date ranges found for gap filling.\n")
    return(invisible(NULL))
  }
  
  # Create batches of stations with overlapping date ranges
  batches <- list()
  current_batch <- 1
  batches[[current_batch]] <- valid_stations[1, ]
  
  for (i in 2:nrow(valid_stations)) {
    current_station <- valid_stations[i, ]
    
    # Check if current station's date range overlaps with any station in current batch
    overlaps <- any(
      current_station$min_date <= batches[[current_batch]]$max_date &
      current_station$max_date >= batches[[current_batch]]$min_date
    )
    
    if (overlaps && nrow(batches[[current_batch]]) < batch_size) {
      # Add to current batch
      batches[[current_batch]] <- rbind(batches[[current_batch]], current_station)
    } else {
      # Start new batch
      current_batch <- current_batch + 1
      batches[[current_batch]] <- current_station
    }
  }
  
  cat("📦 Created", length(batches), "batches for processing\n")
  
  # Process each batch
  for (batch_num in seq_along(batches)) {
    batch <- batches[[batch_num]]
    
    cat("\n🔄 Processing batch", batch_num, "of", length(batches), "\n")
    cat("   Stations:", paste(batch$STATION_NAME, collapse = ", "), "\n")
    cat("   Date range:", as.character(min(batch$min_date)), "to", as.character(max(batch$max_date)), "\n")
    
    # Calculate batch date range
    batch_start <- min(batch$min_date) - 1  # Start one day earlier to ensure coverage
    batch_end <- max(batch$max_date) + 1    # End one day later to ensure coverage
    
    # Convert to FTS API format
    start_date_fts <- paste0(batch_start, "T05:00:00Z")
    end_date_fts <- paste0(batch_end, "T07:00:00Z")
    output_date <- paste0("gap_fill_batch_", batch_num, "_", Sys.Date())
    
    # Download data for this batch
    tryCatch({
      downloadFTS(
        start_date = start_date_fts,
        end_date = end_date_fts,
        output_date = output_date
      )
      
      cat("✅ Batch", batch_num, "downloaded successfully\n")
      
      # Process and upload the downloaded data (reuse existing logic)
      # This will automatically merge the data into the database
      
    }, error = function(e) {
      cat("❌ Error processing batch", batch_num, ":", e$message, "\n")
    })
  }
  
  cat("\n🎉 Gap filling process completed!\n")
}

# Function to run complete gap detection and filling workflow
run_gap_analysis <- function(
  lookback_days = 30,
  start_date = NULL,
  end_date = NULL,
  stations = "all",
  variables = "all",
  auto_fill = TRUE,
  batch_size = 7
) {
  
  cat("🚀 Starting gap analysis workflow...\n")
  cat("=" %R% 50, "\n")
  
  # Step 1: Detect gaps
  gap_results <- detect_data_gaps(
    lookback_days = lookback_days,
    start_date = start_date,
    end_date = end_date,
    stations = stations,
    variables = variables
  )
  
  # Step 2: Fill gaps if requested and gaps exist
  if (auto_fill && nrow(gap_results$gap_summary) > 0) {
    cat("\n" %R% 50, "\n")
    fill_data_gaps(gap_results, batch_size = batch_size)
  } else if (nrow(gap_results$gap_summary) > 0) {
    cat("\n💡 To fill these gaps, run: fill_data_gaps(gap_results)\n")
  }
  
  cat("\n" %R% 50, "\n")
  cat("✅ Gap analysis workflow completed!\n")
  
  return(gap_results)
}

